import assert from 'node:assert/strict';
import test from 'node:test';
import path from 'node:path';
import { openDialogFixture } from './helpers/whatsapp-dialog-browser.mjs';
import { mockDatasheets } from '../lib/whatsapp/mock-documents.ts';

const fixture = 'tests/fixtures/whatsapp-shortcuts.tsx';
const now = Date.UTC(2026, 10, 3, 12);
const document = mockDatasheets[0];
const count = async (page, label) => Number(await page.getByRole('status', { name: label }).textContent());

for (const width of [320, 640]) test(`S9: integrated shortcuts prepare, confirm and preserve existing chat at ${width}px`, { timeout: 25000 }, async t => {
  const { page, errors, external } = await openDialogFixture(t, fixture, width, { now });
  const quote = page.getByRole('button', { name: 'Cotizar', exact: true });
  await quote.waitFor();
  assert.deepEqual(await page.getByRole('group', { name: 'Acciones rápidas' }).getByRole('button').allTextContents(), ['Cotizar', 'Enviar ficha técnica', 'Agendar visita']);
  const details = page.getByRole('button', { name: 'Ficha del cliente', exact: true });
  assert.equal(await details.getAttribute('aria-pressed'), 'false');
  assert.equal(await details.getAttribute('aria-controls'), 'chat-customer-details');
  await details.click();
  assert.equal(await details.getAttribute('aria-pressed'), 'true');
  assert.equal(await page.getByRole('status', { name: 'Ficha abierta' }).textContent(), 'sí');
  await details.click();
  assert.equal(await page.getByRole('status', { name: 'Ficha abierta' }).textContent(), 'no');
  const baseline = await count(page, 'Cantidad de mensajes');
  const draft = page.getByRole('textbox', { name: 'Mensaje de demostración' });
  assert.equal(await draft.isDisabled(), true);
  assert.equal(await draft.getAttribute('placeholder'), 'Toma el chat para escribir');
  assert.equal(await page.getByRole('button', { name: 'Agendar visita', exact: true }).isDisabled(), true);
  await quote.click();
  let dialog = page.getByRole('dialog', { name: 'Crear cotización demo' });
  assert.equal(await dialog.getByRole('textbox', { name: 'Contacto', exact: true }).inputValue(), 'Camila Rojas');
  assert.equal(await dialog.getByRole('textbox', { name: 'Cliente', exact: true }).inputValue(), 'Constructora Los Robles');
  await dialog.getByRole('textbox', { name: 'Descripción', exact: true }).fill('Placas de prueba');
  await dialog.getByRole('spinbutton', { name: 'Cantidad', exact: true }).fill('2');
  await dialog.getByRole('spinbutton', { name: 'Precio unitario (CLP)', exact: true }).fill('1000');
  await dialog.getByRole('button', { name: 'Guardar cotización demo' }).click();
  await dialog.getByText('Cotización demo preparada · $2.380 CLP', { exact: true }).waitFor();
  assert.equal(await count(page, 'Cantidad de mensajes'), baseline);
  assert.equal(await page.getByRole('button', { name: 'Tomar chat', exact: true }).count(), 1, 'Preparing does not claim the chat');
  await page.screenshot({ path: path.resolve(`node_modules/.cache/whatsapp-review/quote-shortcut-${width}.png`) });
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
  assert.equal(await quote.evaluate(node => node === document.activeElement), true);
  await quote.click();
  dialog = page.getByRole('dialog', { name: 'Crear cotización demo' });
  assert.equal(await dialog.getByRole('textbox', { name: 'Descripción', exact: true }).inputValue(), 'Placas de prueba');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Tomar chat', exact: true }).click();
  assert.equal(await draft.getAttribute('placeholder'), 'Escribe tu respuesta…');
  await page.getByRole('button', { name: 'Agendar visita', exact: true }).click();
  assert.equal(await draft.inputValue(), 'Agendar visita a terreno');
  await page.getByRole('button', { name: 'Enviar', exact: true }).click();
  assert.equal(await draft.inputValue(), '');
  assert.equal(await count(page, 'Cantidad de mensajes'), baseline + 2, 'Existing claim event and text send remain unchanged');
  await draft.fill('Borrador sin enviar');
  const sheets = page.getByRole('button', { name: 'Enviar ficha técnica', exact: true });
  await sheets.click();
  dialog = page.getByRole('dialog', { name: 'Enviar ficha técnica' });
  await dialog.getByRole('combobox', { name: 'Producto y documento' }).selectOption(document.id);
  assert.equal(await count(page, 'Cantidad de archivos'), 0);
  assert.equal(await draft.inputValue(), 'Borrador sin enviar');
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
  assert.equal(await count(page, 'Cantidad de archivos'), 0);
  await sheets.click();
  dialog = page.getByRole('dialog', { name: 'Enviar ficha técnica' });
  await dialog.getByRole('combobox', { name: 'Producto y documento' }).selectOption(document.id);
  await page.screenshot({ path: path.resolve(`node_modules/.cache/whatsapp-review/datasheet-shortcut-${width}.png`) });
  await dialog.getByRole('button', { name: 'Confirmar envío demo', exact: true }).click();
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.equal(await count(page, 'Cantidad de archivos'), 1);
  assert.equal(await count(page, 'Cantidad de mensajes'), baseline + 4);
  assert.equal(await page.getByText(`Te comparto ${document.name}. Es una muestra ficticia para revisar el diseño; no es una ficha técnica válida.`, { exact: true }).count(), 1);
  assert.equal(await page.getByText(`▤ ${document.name} · Documento de demostración`, { exact: true }).count(), 1);
  assert.equal(await draft.inputValue(), 'Borrador sin enviar');
  assert.deepEqual(errors, []);
  assert.deepEqual(external, []);
});

test('S9: expiry prevents document confirmation and changing chats discards stale dialogs', { timeout: 25000 }, async t => {
  const { page, errors, external } = await openDialogFixture(t, fixture, 640, { now });
  const sheets = page.getByRole('button', { name: 'Enviar ficha técnica', exact: true });
  await sheets.click();
  let dialog = page.getByRole('dialog', { name: 'Enviar ficha técnica' });
  await dialog.getByRole('combobox', { name: 'Producto y documento' }).selectOption(document.id);
  assert.equal(await dialog.getByRole('button', { name: 'Confirmar envío demo' }).isDisabled(), true);
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await page.getByRole('button', { name: 'Tomar chat', exact: true }).click();
  await sheets.click();
  dialog = page.getByRole('dialog', { name: 'Enviar ficha técnica' });
  await dialog.getByRole('combobox', { name: 'Producto y documento' }).selectOption(document.id);
  assert.equal(await dialog.getByRole('button', { name: 'Confirmar envío demo' }).isDisabled(), false);
  await page.clock.fastForward(3600000);
  await dialog.getByText('Toma la conversación para confirmar el envío demo.', { exact: true }).waitFor();
  assert.equal(await dialog.getByRole('button', { name: 'Confirmar envío demo' }).isDisabled(), true);
  assert.equal(await count(page, 'Cantidad de archivos'), 0);
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await page.getByRole('button', { name: 'Cambiar conversación en 2s' }).click();
  await page.getByRole('button', { name: 'Cotizar', exact: true }).click();
  await page.clock.runFor(2100);
  await page.getByRole('heading', { name: 'Diego Muñoz' }).waitFor();
  assert.equal(await page.getByRole('dialog').count(), 0, 'Old contact preview cannot survive chat navigation');
  await page.getByRole('button', { name: 'Cotizar', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Crear cotización demo' });
  assert.equal(await dialog.getByRole('textbox', { name: 'Contacto', exact: true }).inputValue(), 'Diego Muñoz');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Ver oportunidad', exact: true }).click();
  await page.getByRole('tab', { name: /^WhatsApp/ }).click();
  await page.getByRole('button', { name: 'Ver conversación demo sin vincular' }).click();
  await page.getByRole('button', { name: 'Cotizar', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Crear cotización demo' });
  assert.equal(await dialog.getByRole('textbox', { name: 'Contacto', exact: true }).inputValue(), 'Camila Rojas');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('tabpanel', { name: 'WhatsApp' }).count(), 1);
  assert.equal(await page.getByRole('button', { name: 'Ficha del cliente' }).count(), 0, 'Hosts without a customer card show no toggle');
  assert.equal(await page.getByRole('button', { name: 'Cotizar', exact: true }).isVisible(), true);
  assert.deepEqual(errors, []);
  assert.deepEqual(external, []);
});
